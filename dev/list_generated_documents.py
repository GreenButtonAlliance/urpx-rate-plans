"""Write reports/generated-documents.md: which documents are generated from Clojure source.

Runs the generator (`clojure -M:generate`, through dev/check_generated.py) into a
temporary directory and reads which `:document` var wrote each document. Lists
every generated document with its entry, the clj-urpx release deps.edn pins and
its filing's [generation] sources (doc/dsl-corpus-generation.md), then every
source file with the documents it is a source of.

Refuses, writing nothing, when the generator fails or writes nothing, when a
generated document's filing records no [generation], or when deps.edn pins no
clj-urpx release. dev/check_generated.py is the check that the documents equal
their committed files; this only tabulates.

Run from the repository root:  python3 dev/list_generated_documents.py
Exit codes: 0 written, 3 refused.
"""
from __future__ import annotations

import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_generated  # noqa: E402

REPO = check_generated.REPO
OUT = REPO / "reports" / "generated-documents.md"
DEPS = REPO / "deps.edn"
CLJ_URPX = "energy.grid-coordination/clj-urpx"


def clj_urpx_release() -> str | None:
    m = re.search(re.escape(CLJ_URPX) + r'\s*\{\s*:mvn/version\s+"([^"]+)"', DEPS.read_text())
    return m.group(1) if m else None


def render(by_path: dict[str, str], tables: dict[str, dict], release: str) -> str:
    lines = [
        "# Generated documents",
        "",
        "Auto-generated by `dev/list_generated_documents.py`. Do not edit by hand.",
        "",
        "Each document below is written by `clojure -M:generate` (`src/rate_plans/gen.clj`) "
        f"from the `:document` var named as its entry, with clj-urpx {release}, the release "
        "`deps.edn` pins. Its sources are its filing's `[generation]` sources in `tariff.toml` "
        "([doc/dsl-corpus-generation.md](../doc/dsl-corpus-generation.md)). "
        "`dev/check_generated.py` requires every one to equal its committed file byte for byte.",
        "",
        "## Documents",
        "",
        "| Document | Entry | clj-urpx | Sources |",
        "|---|---|---|---|",
    ]
    by_source: dict[str, list[str]] = {}
    for path in sorted(by_path):
        sources = tables[str(Path(path).parent)]["sources"]
        for src in sources:
            by_source.setdefault(src, []).append(path)
        cells = "<br>".join(f"`{src}`" for src in sources)
        lines.append(f"| `{path}` | `{by_path[path]}` | {release} | {cells} |")
    lines += ["", "## Source files", ""]
    for src in sorted(by_source):
        lines += [f"### `{src}`", ""]
        lines += [f"- `{path}`" for path in by_source[src]]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    release = clj_urpx_release()
    if release is None:
        print(f"refused: deps.edn pins no {CLJ_URPX} release")
        return 3
    with tempfile.TemporaryDirectory(prefix="list-generated.") as tmp:
        by_path = check_generated.generate(Path(tmp))
    if not by_path:
        print("refused: the generator failed or wrote no document")
        return 3
    tables = check_generated.generation_tables()
    unrecorded = sorted(p for p in by_path if str(Path(p).parent) not in tables)
    if unrecorded:
        print("refused: generated documents whose filing records no [generation]:")
        for p in unrecorded:
            print(f"  {p}")
        return 3
    OUT.write_text(render(by_path, tables, release))
    print(f"Wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
