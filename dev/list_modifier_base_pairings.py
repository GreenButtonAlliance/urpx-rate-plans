#!/usr/bin/env python3
"""Generate reports/modifier-base-pairings.{edn,json} from the corpus.

For every urpx:RatePlanModifier in the corpus (whether filed standalone
under its own directory or inline-packaged in a base RatePlan's @graph),
extract the modifier's IRI and the urpx:applicableToRatePlan IRIs declared
on its RatePlanModifierVersion. Emit both views:

  :by-modifier    modifier-IRI → {:applicable-to [base-IRI ...]
                                  :filing "<relative path>"}
  :by-base        base-IRI    → {:modifiers [modifier-IRI ...]}

Consumers (e.g. clj-price-server pairing rate-plans into OpenADR 3
programs) read this file directly instead of walking the JSON-LD.

Run from repo root:  python3 dev/list_modifier_base_pairings.py
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import corpus

REPO = Path(__file__).resolve().parent.parent


# ---------------------------------------------------------------------------
# Corpus walk
# ---------------------------------------------------------------------------

def types_of(node: dict) -> list[str]:
    t = node.get("@type", [])
    return [t] if isinstance(t, str) else list(t)


def applicable_iris_within(node) -> list[str]:
    """Recursively collect every urpx:applicableToRatePlan @id inside `node`."""
    out: list[str] = []
    if isinstance(node, dict):
        if "urpx:applicableToRatePlan" in node:
            v = node["urpx:applicableToRatePlan"]
            for x in (v if isinstance(v, list) else [v]):
                if isinstance(x, dict) and "@id" in x:
                    out.append(x["@id"])
        for v in node.values():
            out.extend(applicable_iris_within(v))
    elif isinstance(node, list):
        for x in node:
            out.extend(applicable_iris_within(x))
    return out


def find_modifiers(node, results: list[tuple[str, list[str]]]) -> None:
    """Recurse and collect (modifier_iri, applicable_base_iris) for every
       urpx:RatePlanModifier-typed node."""
    if isinstance(node, dict):
        if "urpx:RatePlanModifier" in types_of(node):
            iri = node.get("@id")
            if iri:
                results.append((iri, applicable_iris_within(node)))
        for v in node.values():
            find_modifiers(v, results)
    elif isinstance(node, list):
        for x in node:
            find_modifiers(x, results)


def collect() -> tuple[dict[str, dict], dict[str, list[str]]]:
    """Returns (by_modifier, by_base).

    Two-pass walk so the canonical filing pointer for each modifier IRI is
    its dedicated `rate-plan-modifier_*.jsonld` file (when one exists),
    not whichever base happens to inline-bundle it.
    """
    by_modifier: dict[str, dict] = {}
    by_base: dict[str, set[str]] = defaultdict(set)

    def absorb(jsonld_path: Path) -> None:
        with jsonld_path.open() as fp:
            data = json.load(fp)
        results: list[tuple[str, list[str]]] = []
        find_modifiers(data, results)
        rel = str(jsonld_path.relative_to(REPO))
        for iri, applicable in results:
            entry = by_modifier.setdefault(iri, {"applicable_to": [], "filing": rel})
            existing = set(entry["applicable_to"])
            for a in applicable:
                if a not in existing:
                    entry["applicable_to"].append(a)
                    existing.add(a)
                by_base[a].add(iri)

    # Pass 1: dedicated rate-plan-modifier_* files claim canonical filing
    # pointers for the modifiers they contain.
    for jp in corpus.modifier_files():
        absorb(jp)
    # Pass 2: base rate-plan_* files contribute inline modifiers (those without
    # a dedicated filing) and add their applicable_to declarations to existing
    # entries.
    for jp in corpus.rate_plan_files():
        absorb(jp)

    by_base_sorted = {k: sorted(v) for k, v in by_base.items()}
    for iri, entry in by_modifier.items():
        entry["applicable_to"] = sorted(entry["applicable_to"])
    return by_modifier, by_base_sorted


# ---------------------------------------------------------------------------
# Output: EDN
# ---------------------------------------------------------------------------

def iri_to_edn_keyword(iri: str) -> str:
    """`sce:deed-restricted` → `:sce/deed-restricted`."""
    if ":" in iri:
        ns, local = iri.split(":", 1)
        return f":{ns}/{local}"
    return f":{iri}"


def render_edn(by_modifier: dict[str, dict], by_base: dict[str, list[str]]) -> str:
    lines: list[str] = []
    lines.append(";; Auto-generated by dev/list_modifier_base_pairings.py — do not edit by hand.")
    lines.append(";;")
    lines.append(";; Modifier ↔ base pairings derived from urpx:applicableToRatePlan")
    lines.append(";; declarations on each RatePlanModifierVersion in the corpus.")
    lines.append(";;")
    lines.append(";; URPX-style IRIs (e.g. sce:care) are rendered as namespaced Clojure")
    lines.append(";; keywords (e.g. :sce/care) for ergonomic consumption.")
    lines.append("")
    lines.append("{:by-modifier")
    lines.append(" {")
    for iri in sorted(by_modifier.keys()):
        entry = by_modifier[iri]
        applicable = " ".join(iri_to_edn_keyword(a) for a in entry["applicable_to"]) or ""
        kw = iri_to_edn_keyword(iri)
        lines.append(f"  {kw}")
        lines.append(f"  {{:applicable-to [{applicable}]")
        lines.append(f"   :filing {json.dumps(entry['filing'])}}}")
    lines.append(" }")
    lines.append("")
    lines.append(" :by-base")
    lines.append(" {")
    for base_iri in sorted(by_base.keys()):
        modifiers = " ".join(iri_to_edn_keyword(m) for m in by_base[base_iri])
        kw = iri_to_edn_keyword(base_iri)
        lines.append(f"  {kw}")
        lines.append(f"  {{:modifiers [{modifiers}]}}")
    lines.append(" }}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Output: JSON
# ---------------------------------------------------------------------------

def render_json(by_modifier: dict[str, dict], by_base: dict[str, list[str]]) -> str:
    payload = {
        "_comment": (
            "Auto-generated by dev/list_modifier_base_pairings.py. "
            "URPX-style IRIs (e.g. 'sce:care') retained as strings."
        ),
        "by_modifier": {
            iri: {
                "applicable_to": entry["applicable_to"],
                "filing": entry["filing"],
            }
            for iri, entry in sorted(by_modifier.items())
        },
        "by_base": {
            base_iri: {"modifiers": modifiers}
            for base_iri, modifiers in sorted(by_base.items())
        },
    }
    return json.dumps(payload, indent=2) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    by_modifier, by_base = collect()
    edn_path = REPO / "reports" / "modifier-base-pairings.edn"
    json_path = REPO / "reports" / "modifier-base-pairings.json"
    edn_path.write_text(render_edn(by_modifier, by_base))
    json_path.write_text(render_json(by_modifier, by_base))
    print(f"wrote {edn_path.relative_to(REPO)} ({len(by_modifier)} modifiers)")
    print(f"wrote {json_path.relative_to(REPO)} ({len(by_base)} bases referenced)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
