"""Require the three places this corpus states completeness to agree.

Completeness is asserted three times per filing and, until this file existed,
nothing compared them:

  1. urpx:CoverageClaim in the JSON-LD, carrying urpx:completenessResult and,
     when partial, a urpx:Evaluation whose prose says WHAT is missing. This is
     the machine-readable one, required on every version by SHACL, and the one a
     consumer reads to know what it has.
  2. [modeling].complete and [modeling].deferrals in tariff.toml, GENERATED by
     dev/backfill_modeling.py as `complete = not deferrals` from the hand
     curated DEFERRALS table in that file, and the source
     dev/list_ready_for_use.py turns into reports/ready-for-use.md.
  3. What the filing actually contains.

They drift in one direction: somebody models a gap, and the sentence that said
it was unmodeled stays. At 03f5ec3 six modifier filings were in exactly that
state, every CARE and FERA overlay in the corpus. 384ffb1 and f62a603 added the
percentage discount to all six as a urpx:multiplier; a8b33d0 and e19b6ec had
written their coverage evaluations one and two commits earlier, and none of the
six was revised. So the machine-readable answer and the prose answer disagreed
across the whole family. Nothing failed, because each artifact is internally
valid and no check read both.

WHAT IS CHECKED

  MULTIPLIER-VS-PROSE  A version carries a urpx:Price with urpx:multiplier while
                       its own coverage evaluation says that same percentage is
                       not represented. Signal 1 against signal 3.
  MANIFEST-VS-CLAIM    [modeling].complete disagrees with the
                       urpx:completenessResult of the filing's own claim.
                       Signal 2 against signal 1.
  MANIFEST-INTERNAL    [modeling].complete is true while [modeling].deferrals
                       lists something. Signal 2 against itself, and free.
  MANIFEST-PROSE       [modeling].complete is true and [modeling].deferrals is
                       empty while the manifest's own free text still carries a
                       "Modeling deferrals" section that lists something. Signal
                       2 against the prose in the same file.

MANIFEST-PROSE EXISTS BECAUSE THE OTHER THREE LEAVE A HOLE. A coverage claim
that is urpx:complete can carry no urpx:Evaluation at all, so for those filings
signal 1 says only "complete" and there is no prose on that side to
compare signal 2 against. MULTIPLIER-VS-PROSE reaches a filing only where a
urpx:multiplier happens to exist. The manifest's
own free text is the second side that is always there: a manifest that heads a
list "Modeling deferrals" and then reports complete = true with deferrals = []
contradicts itself inside one file, and no PDF is needed to see it. Measured at
the commit that added this check: 32 such sections carrying 127 items across 31
filing directories, and 8 manifests whose flag says complete with nothing
deferred while such a section still lists something. The corpus settles the
question against itself: sdge:dr and sdge:tou-dr1 record PCIA for CCA-served
customers as a structured deferral, while dr-ses, ev-tou-5, tou-dr2 and
tou-elec record the same provision of the same rate case in prose only and call
themselves complete.

THE WHOLE JOB IS FALSE POSITIVES. Two shapes look like disagreement and are not,
and a check that reports either one is worse than no check, because it teaches
people to run the gate with their eyes shut.

  A DIRECTORY HOLDS MORE THAN ONE CLAIM. pge:e-tou-c 2026-03-27 packages the
  base plan together with the pge:e-tou-c-vintage-pcia modifier, so its one
  JSON-LD file carries a urpx:complete claim and a urpx:partial one. The
  manifest's complete = true is correct: it describes the base plan, not the
  modifier riding along in the same document. So MANIFEST-VS-CLAIM does not
  compare the manifest against every claim in the directory. It resolves the
  filing's PRIMARY document by filename (the one whose slug is the manifest's
  own schedule and date, which is unique per filing directory), then
  takes the single claim reachable by the structural path matching that
  document's kind: hasRatePlan/hasRatePlanVersion/hasCoverageClaim for a base
  filing, hasRatePlanModifier/hasRatePlanModifierVersion/hasCoverageClaim for a
  modifier one. Every other claim in the document belongs to something else and
  is out of scope by construction rather than by a list of exceptions.
  Measured at 03f5ec3, the naive directory-wide rule reports two disagreements
  and this one reports one; the one it drops is pge:e-tou-c 2026-03-27.

  AN EVALUATION LEGITIMATELY NAMES SOMETHING UNMODELED. Every partial evaluation
  does, which is the point of writing one. The SDG&E CARE and FERA evaluations
  each list a 50 percent minimum bill alternative among the provisions they say
  are absent, which is true and has nothing to do with the 35 and 18 percent
  multipliers those same filings carry.
  So MULTIPLIER-VS-PROSE is anchored on the NUMBER, not on the presence of
  unmodeled things: it derives the percentage from the multiplier itself
  (-0.325 gives 32.5, -0.18 gives 18 and 18.0) and only looks at sentences that
  state that percentage as a percentage. "0.35000" in prose is deliberately not
  matched, because the SDG&E CARE evaluation uses that form for the
  non-residential discount, which is a different and genuinely absent thing.

  The absence assertion must then land in the SAME SENTENCE as the percentage.
  Sentence scope is what binds the predicate to the number; at document scope
  every partial evaluation matches something. The limit of that is a false
  NEGATIVE, stated rather than hidden: prose that names the percentage in one
  sentence and denies it in the next is not caught. All six live instances put
  both in one sentence.

  Finally a sentence that carries an absence predicate AND, outside that
  predicate's own span, a presence predicate is not counted. That is the shape a
  CORRECTED evaluation takes, "modeled here as a multiplier over the
  discountable subtotal, while the non-residential structure remains absent",
  and failing it would make the gate unpassable on correct data. Suppression is
  never silent: every suppressed sentence is printed and counted, so a
  suppression that is wrong is visible in the same output as the verdict.

  PROSE MENTIONS A DEFERRAL FOR MANY REASONS, AND ONLY ONE OF THEM IS A CLAIM.
  Extraction notes legitimately discuss what the source contains, what was hard
  to read, what a SIBLING filing defers, and what was deferred and has since
  been modeled. Scanning free text for words like "deferred" or "not modeled"
  finds all of that: run over the corpus's manifests, a bare vocabulary scan hits
  filings whose every mention is a cross-reference. So MANIFEST-PROSE does not
  scan free text. It looks for one thing this corpus authors deliberately, a
  heading that says "Modeling deferrals", in either spelling the corpus uses
  ("## Modeling deferrals" and "Modeling deferrals (...):"), and reads only the
  items under it. The heading is the author declaring what follows; a sentence
  elsewhere that happens to use the word is prose and is never read. That is why
  "Nothing Special Condition 9 prices is deferred" in the SCE FERA notes and
  "## What this modifier does NOT capture (out of scope)" in the SCE
  deed-restricted notes are both invisible to this check rather than suppressed
  by a rule about negation or about scope.

  Inside the section the default is reversed, and deliberately. An item under
  that heading COUNTS unless it says the thing is in the graph, because the
  terse half of the corpus writes a deferral as a bare noun phrase with no
  predicate at all ("PCIA (Special Condition 11) for CCA-served customers.").
  Requiring an absence predicate would read those four SDG&E filings as clean
  while flagging the two that spell the same deferral out in a sentence, which
  teaches people that a shorter bullet is a safer bullet.

  The presence guard is how a section stops firing without anyone deleting it.
  dr-ses and tou-elec each carry a minimum-stay bullet that was a deferral and
  now reads "MODELED, as urpx:minimumTenure", and that bullet should not keep
  the gate red. The words are cheap, though, and the suppression is where the
  whole risk sits, so a presence claim is believed only when this corpus can
  check it and the check passes. Four shapes wear the word "modeled" and are
  deferrals anyway.
    NEGATED      "Not modeled here" is the opposite claim, and only the couple
                 of words in front of the phrase separate the two.
    FUTURE       "modeled in a future cross-utility GHG-ARR modifier issue" and
                 "not yet modeled as an EligibilityRule" name a plan, not a
                 state.
    TRACKER      "modeled as standalone RatePlanModifiers in the
                 grid-coordination/urpx-rate-plans#13 secondary epic" points at
                 an issue, and an issue is where unmodeled things are recorded.
    UNCHECKABLE  A claim naming no corpus path and no urpx: term says the thing
                 is modeled somewhere without saying where, so there is nothing
                 to compare it against.
  The last one is not hypothetical. "Schedule NEM billing combination (SC 9),
  DR-SES + NEM modeled as independent filings" suppressed a bullet by pointing
  at a filing this corpus does not contain: no manifest under us/ca/sdge carries
  schedule = "nem", the successor schedule nbt being the one SDG&E solar filing
  here, so the other half of "independent filings" is not there to be read.
  Believing a presence claim is believing a statement about the corpus, so it is
  resolved against the corpus.

  A suppression therefore has to name WHERE, in one of the two forms that
  resolve: a corpus path, which must be a directory holding at least one
  tariff.toml, and a urpx: term, which must appear in the JSON-LD of this filing
  or of a path the item itself names. Every location named must check out; one
  that does not is reported, with the location printed. A filing directory
  holding no JSON-LD at all refuses instead, because then the check cannot run
  rather than having run and failed. Suppressed items are printed with what was
  verified, and an item carrying a presence phrase that is reported anyway
  prints why the phrase was not believed, so both directions of the judgment are
  visible in the same output as the verdict.

  THE LIMIT, STATED RATHER THAN HIDDEN: this check does not judge whether an
  item is a deferral of THIS filing or a note about corpus coverage. It cannot,
  because "A-1 large TOU residential, EZ-Save Lifeline, NEM Service Rider" and
  "90-day initial-term opt-out window (SC 6)" are the same shape in prose and
  differ only in whether the named thing belongs to this document, which needs
  the document. Anchoring on a source citation ("Sheet 7", "SC 6") was tried and
  is worse: it drops the ladwp:r-1a noise and also drops both live items in the
  sce:d 2025-11-15 section, which carry no citation. One of today's 8 findings,
  ladwp:r-1a, is that shape: its two items are other LADWP schedules and a
  deferred HTML source capture, and the honest fix there is to rename the
  heading rather than to change the flag. The check says which items it read, so
  that judgment is the reader's and takes one look.

DENOMINATORS ARE PRINTED. Four checks in this repository have at some point
passed while comparing nothing, so a bare "clean" is not evidence. The report
names how many filings, versions, claims, evaluations, multipliers and manifest
flags were actually compared. A collapsed denominator refuses with exit 3 rather
than reporting clean: no filings, no manifests, no claims, no [modeling].complete
anywhere, or no multiplier in the corpus at all. That last one is a real
possibility only through breakage: zero means the property name or
the traversal moved, not that California stopped discounting bills. A
multiplier-bearing version whose claim is partial but carries no evaluation prose
also refuses, because for that version the comparison has no second side. So does
a corpus in which no manifest carries a "Modeling deferrals" section at all:
zero means the heading convention or the notes field moved, which
would leave MANIFEST-PROSE reading nothing while reporting clean. So does an
eligible manifest whose "Modeling deferrals" section has a body and yields no
readable item, which is the section the colon rule empties out: "Same 4 deferrals
as the DA-CRS sibling (see us/ca/.../tariff.toml):" is an introducer with the
content in another file, and reading it as an empty section would pass a filing
that declares four deferrals. The count of
manifests eligible for it, complete with an empty deferrals list, is printed
rather than refused on, because a corpus in which every filing is partial is a
legitimate state and not a broken traversal.

Exit: 0 clean, 1 a disagreement, 3 refused.

Usage:
    python3 dev/lint_completeness_agreement.py [--json]
"""
