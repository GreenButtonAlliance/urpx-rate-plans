def primary_document(filing_dir: Path, schedule: str, date: str) -> Path:
    """The document the manifest is about, by filename.

    A directory may package a sibling modifier under its own slug. Only the
    document whose slug is the manifest's own schedule and date is the subject.
    """
    pattern = re.compile(
        r"rate-plan(-modifier)?_[a-z0-9-]+?_"
        + re.escape(schedule) + r"_" + re.escape(date) + r"\.jsonld$")
    matches = [p for p in sorted(filing_dir.glob("*.jsonld")) if pattern.match(p.name)]
    if len(matches) != 1:
        raise ValueError(
            f"{filing_dir.relative_to(REPO)}: expected exactly one document named "
            f"for schedule {schedule!r} at {date!r}, found {len(matches)} "
            f"({[p.name for p in matches]}). The manifest's subject is ambiguous, "
            f"so there is no claim to compare it against.")
    return matches[0]


def primary_claim(doc, is_modifier: bool):
    want = MOD_CLAIM_PATH if is_modifier else BASE_CLAIM_PATH
    hits = [n for n, p in collect(doc, lambda n, p: node_type(n) == "urpx:CoverageClaim")
            if p[-len(want):] == want]
    return hits


def manifest_findings(filing_dirs):
    findings, internal, prose, prose_suppressed = [], [], [], []
    tally = {
        "manifests": 0,
        "with_complete_flag": 0,
        "compared": 0,
        "complete_true": 0,
        "complete_false": 0,
        "text_fields": 0,
        "deferral_sections": 0,
        "deferral_section_items": 0,
        "prose_eligible": 0,
        "prose_presence_verified": 0,
        "prose_presence_declined": 0,
    }
    unanswerable = []

    for d in filing_dirs:
        manifest = d / "tariff.toml"
        tally["manifests"] += 1
        data = toml_reader.loads(manifest.read_text())
        modeling = data.get("modeling") or {}
        complete = modeling.get("complete")
        schedule = data.get("schedule")
        date = data.get("effective_date")
        rel = str(d.relative_to(REPO))

        # MANIFEST-PROSE. Counted for every manifest so the denominator is the
        # corpus, not the subset that happens to trip; the finding itself is
        # raised only where the flag says complete with nothing deferred.
        sections = []
        for key, text in manifest_strings(data):
            tally["text_fields"] += 1
            for heading, body in deferral_sections(text):
                items = section_items(body)
                tally["deferral_sections"] += 1
                tally["deferral_section_items"] += len(items)
                sections.append((key, heading, body, items))
        deferrals_listed = modeling.get("deferrals") or []
        if complete is True and not deferrals_listed:
            tally["prose_eligible"] += 1
            claimed = []
            for key, heading, body, items in sections:
                if body and not items:
                    # The section declares deferrals and this check read none of
                    # them, so it has nothing to report and no grounds to pass.
                    unanswerable.append(
                        f"{rel}: [{key}] heads {heading!r} over {len(body)} line(s) "
                        f"that yield no readable item, so MANIFEST-PROSE compared "
                        f"nothing on a manifest that reports complete")
                    continue
                for it in items:
                    excuse, declined, blocked = prose_item_verdict(it, d)
                    if blocked:
                        unanswerable.append(blocked)
                        continue
                    if excuse:
                        tally["prose_presence_verified"] += 1
                        prose_suppressed.append(
                            {"dir": rel, "field": key, "presence": excuse, "item": it})
                    else:
                        if declined:
                            tally["prose_presence_declined"] += 1
                        claimed.append({"field": key, "heading": heading, "item": it,
                                        "declined": declined})
            if claimed:
                prose.append({"dir": rel, "items": claimed})

        if complete is None:
            unanswerable.append(f"{rel}: tariff.toml has no [modeling].complete")
            continue
        tally["with_complete_flag"] += 1
        tally["complete_true" if complete else "complete_false"] += 1

        deferrals = modeling.get("deferrals") or []
        if complete and deferrals:
            internal.append({"dir": rel, "deferrals": list(deferrals)})

        if not schedule or not date:
            unanswerable.append(f"{rel}: tariff.toml has no schedule or effective_date")
            continue
        try:
            primary = primary_document(d, str(schedule), str(date))
        except ValueError as e:
            unanswerable.append(str(e))
            continue

        doc = json.loads(primary.read_text())
        claims = primary_claim(doc, primary.name.startswith("rate-plan-modifier_"))
        if len(claims) != 1:
            unanswerable.append(
                f"{rel}: {primary.name} has {len(claims)} claims on the version "
                f"path for its own kind; expected exactly one")
            continue

        tally["compared"] += 1
        result = claim_result(claims[0])
        expected = "urpx:complete" if complete else "urpx:partial"
        if result != expected:
            findings.append({
                "dir": rel,
                "document": primary.name,
                "complete": bool(complete),
                "expected": expected,
                "result": result,
                "claim": claims[0].get("@id"),
                "deferrals": list(deferrals),
            })

    return findings, internal, prose, prose_suppressed, tally, unanswerable


