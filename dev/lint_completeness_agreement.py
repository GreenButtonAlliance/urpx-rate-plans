def manifest_strings(data, prefix=""):
    """Every string in a parsed manifest, with its dotted key path.

    Walking the whole document rather than naming [extraction].notes and
    [review].notes means a renamed or added notes field keeps being read
    instead of silently dropping out of the denominator.
    """
    if isinstance(data, dict):
        for k, v in data.items():
            yield from manifest_strings(v, f"{prefix}.{k}" if prefix else str(k))
    elif isinstance(data, list):
        for v in data:
            yield from manifest_strings(v, prefix)
    elif isinstance(data, str):
        yield prefix, data


def deferral_sections(text):
    """(heading, body lines) for each "Modeling deferrals" section in one string.

    A section runs from its heading to the next markdown heading or the next
    blank line after its content, which is how all three layouts the corpus
    uses terminate: heading then bullets, heading then blank then bullets, and
    heading then a paragraph.
    """
    lines = text.splitlines()
    out, i = [], 0
    while i < len(lines):
        if not PROSE_HEADING.match(lines[i]):
            i += 1
            continue
        heading = lines[i].strip()
        j = i + 1
        while j < len(lines) and not lines[j].strip():
            j += 1
        body = []
        while j < len(lines) and lines[j].strip() and not MD_HEADING.match(lines[j]):
            body.append(lines[j])
            j += 1
        out.append((heading, body))
        i = max(j, i + 1)
    return out


def section_items(body):
    """Split a section body into items, joining each bullet's continuation lines.

    A body with no bullets is one item, which is the shape a section takes when
    it is written as a paragraph. A line ending in a colon introduces what
    follows rather than stating anything, so it is dropped: the 7 such items in
    the corpus are all of that shape, "Same as TOU-DR1:" and "Deferred to
    grid-coordination/urpx-rate-plans#15 (SMUD secondary epic):".
    """
    items, cur = [], None
    for line in body:
        if PROSE_BULLET.match(line):
            if cur is not None:
                items.append(cur)
            cur = PROSE_BULLET.sub("", line).strip()
        elif cur is not None:
            cur += " " + line.strip()
        else:
            cur = line.strip()
    if cur is not None:
        items.append(cur)
    out = []
    for it in items:
        it = " ".join(it.split())
        if it and not it.endswith(":"):
            out.append(it)
    return out


def rel_to_repo(p: Path) -> str:
    """A repository-relative path for a message, without raising on one from outside."""
    try:
        return str(p.relative_to(REPO))
    except ValueError:
        return str(p)


def corpus_dir_holds_filing(rel: str) -> bool:
    """True when a path an item names is a directory of this corpus with a filing in it."""
    d = (REPO / rel).resolve()
    if REPO not in d.parents and d != REPO:
        return False  # a "../" escaped the corpus; not a location here
    return d.is_dir() and any(d.glob(f"**/{corpus.TARIFF_MANIFEST}"))


def jsonld_text(d: Path) -> str | None:
    """Every JSON-LD document at or under a directory, concatenated; None if there are none."""
    docs = sorted(d.glob("**/*.jsonld"))
    if not docs:
        return None
    return "\n".join(p.read_text() for p in docs)


def prose_item_verdict(item: str, filing_dir: Path) -> tuple[str | None, str | None, str | None]:
    """Whether an item under a "Modeling deferrals" heading has been answered.

    Returns (excuse, declined, blocked), exactly one of which is set, or all
    three None when the item carries no presence phrase at all and is simply a
    deferral.

      excuse    the item says the thing is in the graph and the corpus agrees;
                the text names the phrase and what was verified.
      declined  the item wears the word "modeled" and is a deferral anyway;
                the text says which of the four shapes it is.
      blocked   the claim is checkable in principle and the check could not run,
                which refuses rather than suppressing.
    """
    hit = ITEM_PRESENCE.search(item)
    if not hit:
        return None, None, None
    phrase = hit.group(0)

    neg = ITEM_NEGATED.search(item[:hit.start()])
    if neg:
        return None, f"negated: {' '.join((neg.group(0) + phrase).split())!r}", None
    fut = ITEM_FUTURE.search(item)
    if fut:
        return None, f"names a plan, not a state: {fut.group(0)!r}", None
    trk = ITEM_TRACKER.search(item)
    if trk:
        return None, f"its WHERE is a tracker item: {trk.group(0)!r}", None

    paths = sorted({m.group(0).rstrip("/") for m in CORPUS_PATH.finditer(item)})
    terms = sorted(set(URPX_TERM.findall(item)))
    if not paths and not terms:
        return None, ("names no corpus path and no urpx: term, so where it is "
                      "modeled cannot be checked"), None

    verified = []
    for rel in paths:
        if not corpus_dir_holds_filing(rel):
            return None, f"names {rel}/, which holds no filing in this corpus", None
        verified.append(rel + "/")
    if terms:
        blob = []
        for d in [filing_dir] + [REPO / rel for rel in paths]:
            text = jsonld_text(d)
            if text is None:
                if d == filing_dir:
                    return None, None, (
                        f"{rel_to_repo(filing_dir)}: an item under "
                        f"\"Modeling deferrals\" claims {', '.join(terms)} is modeled "
                        f"and the directory holds no JSON-LD, so the claim cannot be "
                        f"checked")
                continue
            blob.append(text)
        joined = "\n".join(blob)
        for term in terms:
            if term not in joined:
                return None, (f"names {term}, which appears in no JSON-LD of this "
                              f"filing" + (f" or of {', '.join(paths)}" if paths else "")), None
        verified.extend(terms)

    return f"{phrase} -> {', '.join(verified)}", None, None


