class Refused(Exception):
    pass


def run():
    files = corpus.all_filing_jsonld()
    corpus.require_nonempty(files, "rate-plan filings")
    dirs = corpus.filing_dirs()
    corpus.require_nonempty(dirs, "filing directories")

    mult, suppressed, mtally, munans = multiplier_findings(files)
    man, internal, prose, prose_sup, ttally, tunans = manifest_findings(dirs)

    unanswerable = munans + tunans
    if unanswerable:
        raise Refused(
            "the comparison has no second side for "
            f"{len(unanswerable)} filing(s):\n    "
            + "\n    ".join(unanswerable))

    # Denominator collapse. Each of these makes one whole check vacuous, and a
    # vacuous check reporting "clean" is the failure mode this file exists to
    # avoid elsewhere.
    if mtally["versions_with_claim"] == 0:
        raise Refused("no urpx:CoverageClaim found on any version; the traversal "
                      "or the property name moved")
    if mtally["versions_with_multiplier"] == 0:
        raise Refused(
            "no urpx:Price carries urpx:multiplier anywhere in the corpus, so "
            "MULTIPLIER-VS-PROSE compared nothing. Six such prices exist in the "
            "CARE and FERA modifier filings, so zero means the property name or "
            "the traversal changed rather than that the discounts went away.")
    if ttally["with_complete_flag"] == 0:
        raise Refused("no tariff.toml carries [modeling].complete; the manifest "
                      "key moved")
    if ttally["deferral_sections"] == 0:
        raise Refused(
            "no tariff.toml carries a \"Modeling deferrals\" section, so "
            "MANIFEST-PROSE read nothing. 32 such sections exist across 31 "
            "filing directories, so zero means the heading convention or the "
            "notes field moved rather than that the corpus stopped deferring.")

    return {
        "multiplier_vs_prose": mult,
        "suppressed": suppressed,
        "manifest_vs_claim": man,
        "manifest_internal": internal,
        "manifest_prose": prose,
        "prose_suppressed": prose_sup,
        "counts": {
            "filings": len(files),
            "filing_dirs": len(dirs),
            **{f"jsonld_{k}": v for k, v in mtally.items()},
            **{f"manifest_{k}": v for k, v in ttally.items()},
        },
    }


def report(res) -> int:
    c = res["counts"]
    mult = res["multiplier_vs_prose"]
    man = res["manifest_vs_claim"]
    internal = res["manifest_internal"]
    prose = res["manifest_prose"]
    sup = res["suppressed"]
    psup = res["prose_suppressed"]

    print("Completeness agreement")
    print(f"  compared {c['filings']} JSON-LD filings across "
          f"{c['filing_dirs']} filing directories\n")
    print("  MULTIPLIER-VS-PROSE")
    print(f"      versions                                 {c['jsonld_versions']}")
    print(f"      with a urpx:CoverageClaim                {c['jsonld_versions_with_claim']}")
    print(f"      carrying a urpx:multiplier price         "
          f"{c['jsonld_versions_with_multiplier']} "
          f"({c['jsonld_multiplier_prices']} prices)")
    print(f"      with evaluation prose to compare         {c['jsonld_comparable']}")
    print(f"      complete claim, no prose to contradict   {c['jsonld_complete_no_prose']}")
    print(f"      sentences naming the multiplier percent  "
          f"{c['jsonld_sentences_naming_percentage']}")
    print(f"      sentences suppressed by a presence claim {len(sup)}")
    print("  MANIFEST-VS-CLAIM")
    print(f"      tariff.toml manifests                    {c['manifest_manifests']}")
    print(f"      carrying [modeling].complete             {c['manifest_with_complete_flag']}"
          f"  (true {c['manifest_complete_true']}, false {c['manifest_complete_false']})")
    print(f"      compared against a primary claim         {c['manifest_compared']}")
    print("  MANIFEST-PROSE")
    print(f"      manifest text fields read                {c['manifest_text_fields']}")
    print(f"      \"Modeling deferrals\" sections found       "
          f"{c['manifest_deferral_sections']} "
          f"({c['manifest_deferral_section_items']} items)")
    print(f"      manifests eligible (complete, none listed) "
          f"{c['manifest_prose_eligible']}")
    print(f"      items suppressed by a VERIFIED presence   {len(psup)}")
    print(f"      presence claims declined, still reported "
          f"{c['manifest_prose_presence_declined']}")
    print()

    if sup:
        print(f"  {len(sup)} sentence(s) named a multiplier's percentage beside an")
        print("  absence predicate but also asserted presence outside it, and were")
        print("  NOT counted. Read them; a wrong suppression hides a real defect:")
        for s in sup:
            print(f"    {s['file']}")
            print(f"        {s['price']}  multiplier {s['multiplier']}")
            print(f"        absence {s['absence']!r} vs presence {s['presence']!r}")
            print(f"        {s['sentence']}")
        print()

    if psup:
        print(f"  {len(psup)} item(s) under a \"Modeling deferrals\" heading assert "
              f"the thing is")
        print("  in the graph, name where, and the corpus agrees, so they were NOT")
        print("  counted. Read them; a wrong suppression hides a real defect:")
        for s in psup:
            print(f"    {s['dir']}  [{s['field']}]  verified {s['presence']!r}")
            print(f"        {s['item']}")
        print()

    if not mult and not man and not internal and not prose:
        # The counts go on the verdict line itself. dev/gate.sh shows the last
        # line of a passing step, and "clean" with no denominator beside it is
        # indistinguishable from a check that compared nothing.
        print(f"Completeness agreement: clean "
              f"({c['jsonld_multiplier_prices']} multiplier price(s) vs their own "
              f"evaluation prose, {c['manifest_compared']} manifest flag(s) vs "
              f"their own primary claim, {c['manifest_deferral_section_items']} "
              f"prose item(s) in {c['manifest_deferral_sections']} section(s) vs "
              f"{c['manifest_prose_eligible']} eligible manifest(s), "
              f"{len(sup) + len(psup)} suppressed)")
        return 0

    if mult:
        print(f"  MULTIPLIER-VS-PROSE: {len(mult)} filing(s) model a percentage "
              f"discount their own coverage evaluation denies\n")
        for f in mult:
            print(f"  {f['file']}")
            print(f"      price   {f['price']}")
            print(f"      states  urpx:multiplier {f['multiplier']}, "
                  f"which is {f['percent']} percent")
            print(f"      claim   {f['claim']}  ({f['result']})")
            print(f"      denies  {f['absence']!r} in:")
            print(f"        {f['sentence']}")
            print()
        print("  The multiplier is the machine-readable answer and the evaluation is")
        print("  the one a reader gets. Revise the sentence, or remove the price.")
        print()

    if man:
        print(f"  MANIFEST-VS-CLAIM: {len(man)} manifest(s) disagree with their "
              f"own filing's claim\n")
        for f in man:
            print(f"  {f['dir']}")
            print(f"      tariff.toml  [modeling].complete = "
                  f"{str(f['complete']).lower()}  (expects {f['expected']})")
            print(f"      {f['document']}  {f['claim']} = {f['result']}")
            if f["deferrals"]:
                for d in f["deferrals"]:
                    print(f"      deferral: {d}")
            print()
        print("  dev/list_ready_for_use.py gates reports/ready-for-use.md on")
        print("  [modeling].complete, so a manifest that overstates completeness")
        print("  publishes that overstatement. Fix the CLAIM, or fix the DEFERRALS")
        print("  table in dev/backfill_modeling.py: [modeling] is generated from it")
        print("  as `complete = not deferrals`, and dev/check_all.py regenerates it,")
        print("  so editing tariff.toml by hand is undone on the next --full run.")
        print()

    if internal:
        print(f"  MANIFEST-INTERNAL: {len(internal)} manifest(s) claim complete "
              f"while listing deferrals\n")
        for f in internal:
            print(f"  {f['dir']}")
            for d in f["deferrals"]:
                print(f"      deferral: {d}")
            print()

    if prose:
        print(f"  MANIFEST-PROSE: {len(prose)} manifest(s) report complete with an "
              f"empty deferrals\n  list while their own notes still head a list "
              f"\"Modeling deferrals\"\n")
        for f in prose:
            print(f"  {f['dir']}")
            for it in f["items"]:
                print(f"      [{it['field']}]  under {it['heading']!r}")
                print(f"        {it['item']}")
                if it.get("declined"):
                    print(f"        ^ says \"modeled\" and is counted anyway: "
                          f"{it['declined']}")
            print()
        print("  Each item above is what the manifest itself says it did not model,")
        print("  printed verbatim so the call is one look. This check does not judge")
        print("  whether an item is a deferral of THIS filing or a note about corpus")
        print("  coverage, which needs the source document. Three fixes are possible")
        print("  and which one applies is per item: record it in the DEFERRALS table")
        print("  in dev/backfill_modeling.py, which sets `complete = not deferrals`;")
        print("  or rewrite the item to say where it IS modeled, which clears it the")
        print("  way the dr-ses minimum-stay bullet was cleared; or move it out from")
        print("  under the heading, if the heading is what is wrong. An item marked")
        print("  ^ already says \"modeled\" and did not clear: saying where, as a")
        print("  corpus path or a urpx: term that is actually there, is what clears")
        print("  it, and naming an issue instead is a deferral with a ticket number.")
        print()

    return 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    try:
        res = run()
    except (Refused, SystemExit) as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 3
    except Exception as e:  # noqa: BLE001 - refusing is a distinct outcome
        print(f"REFUSED: {type(e).__name__}: {e}", file=sys.stderr)
        return 3

    if args.json:
        print(json.dumps(res, indent=2))
        return 1 if (res["multiplier_vs_prose"] or res["manifest_vs_claim"]
                     or res["manifest_internal"] or res["manifest_prose"]) else 0
    return report(res)


if __name__ == "__main__":
    raise SystemExit(main())
