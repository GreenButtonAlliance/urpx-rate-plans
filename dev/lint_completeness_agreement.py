def percent_forms(multiplier) -> list[str]:
    """The spellings a multiplier's percentage takes in prose.

    -0.325 -> 32.5;  -0.18 -> 18 and 18.0;  -0.35 -> 35 and 35.0.
    """
    pct = (abs(Decimal(str(multiplier))) * 100).normalize()
    plain = format(pct, "f")
    forms = {plain}
    if "." in plain:
        forms.add(plain.rstrip("0").rstrip("."))
    else:
        forms.add(plain + ".0")
    return sorted(forms)


def percent_regex(forms) -> re.Pattern:
    alt = "|".join(re.escape(f) for f in forms)
    # (?<![\d.]) keeps "18" from matching inside "118" or "0.18".
    return re.compile(rf"(?<![\d.])(?:{alt})\s*(?:percent\b|per cent\b|%)", re.IGNORECASE)


def strip_absence(sentence: str) -> str:
    return ABSENCE.sub(" ", sentence)


def multiplier_findings(files):
    """Every version whose own evaluation denies its own multiplier.

    Returns (findings, suppressed, tallies). Pairing is per VERSION: the claim
    compared against a multiplier is the claim on the same version node, never a
    claim elsewhere in the document, so a packaged sibling's evaluation can
    never be read as a statement about this version's prices.
    """
    findings, suppressed = [], []
    tally = {
        "versions": 0,
        "versions_with_claim": 0,
        "multiplier_prices": 0,
        "versions_with_multiplier": 0,
        "comparable": 0,
        "partial_without_prose": 0,
        "complete_no_prose": 0,
        "sentences_naming_percentage": 0,
    }
    unanswerable = []

    for path in files:
        doc = json.loads(path.read_text())
        rel = str(path.relative_to(REPO))
        for version, _ in collect(doc, lambda n, p: node_type(n) in VERSION_TYPES):
            tally["versions"] += 1
            claim = version.get("urpx:hasCoverageClaim")
            if isinstance(claim, list):
                claim = claim[0] if claim else None
            if isinstance(claim, dict):
                tally["versions_with_claim"] += 1

            prices = [n for n, _ in collect(
                version,
                lambda n, p: node_type(n) == "urpx:Price" and "urpx:multiplier" in n)]
            if not prices:
                continue
            tally["versions_with_multiplier"] += 1
            tally["multiplier_prices"] += len(prices)

            if not isinstance(claim, dict):
                unanswerable.append(
                    f"{rel}: version {version.get('@id')} carries "
                    f"{len(prices)} multiplier price(s) and no urpx:CoverageClaim")
                continue
            prose = evaluation_text(claim)
            if prose is None:
                if claim_result(claim) == "urpx:complete":
                    # Nothing asserted in prose, so nothing to contradict.
                    tally["complete_no_prose"] += 1
                    continue
                tally["partial_without_prose"] += 1
                unanswerable.append(
                    f"{rel}: claim {claim.get('@id')} is "
                    f"{claim_result(claim)} and carries no urpx:Evaluation "
                    f"description, so its multiplier cannot be compared to prose")
                continue

            tally["comparable"] += 1
            sentences = SENTENCE_SPLIT.split(prose)
            for price in prices:
                raw = price.get("urpx:multiplier")
                try:
                    forms = percent_forms(raw)
                except (InvalidOperation, ValueError):
                    unanswerable.append(
                        f"{rel}: price {price.get('@id')} has an unreadable "
                        f"urpx:multiplier {raw!r}")
                    continue
                pat = percent_regex(forms)
                for sentence in sentences:
                    if not pat.search(sentence):
                        continue
                    tally["sentences_naming_percentage"] += 1
                    hit = ABSENCE.search(sentence)
                    if not hit:
                        continue
                    record = {
                        "file": rel,
                        "version": version.get("@id"),
                        "price": price.get("@id"),
                        "multiplier": str(raw),
                        "percent": "/".join(forms),
                        "claim": claim.get("@id"),
                        "result": claim_result(claim),
                        "absence": hit.group(0),
                        "sentence": sentence.strip(),
                    }
                    guard = PRESENCE.search(strip_absence(sentence))
                    if guard:
                        record["presence"] = guard.group(0)
                        suppressed.append(record)
                    else:
                        findings.append(record)

    return findings, suppressed, tally, unanswerable


