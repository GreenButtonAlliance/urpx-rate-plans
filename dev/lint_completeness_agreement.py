import json
import re
import sys
from decimal import Decimal, InvalidOperation
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "dev"))
import corpus  # noqa: E402

try:
    import tomllib as toml_reader  # Python 3.11+
except ModuleNotFoundError:  # pragma: no cover
    import tomli as toml_reader  # type: ignore[no-redef]

VERSION_TYPES = ("urpx:RatePlanVersion", "urpx:RatePlanModifierVersion")

# The structural path from a document root to the claim that describes THE
# FILING, per document kind. Anything else in the document is a packaged
# sibling and is not the manifest's subject.
BASE_CLAIM_PATH = ("urpx:hasRatePlan", "urpx:hasRatePlanVersion", "urpx:hasCoverageClaim")
MOD_CLAIM_PATH = ("urpx:hasRatePlanModifier", "urpx:hasRatePlanModifierVersion",
                  "urpx:hasCoverageClaim")

# Sentence boundary: a terminator followed by whitespace and an opening capital.
# Deliberately blind to "$0.212" and "D.24-05-028", where the period is followed
# by a digit or no space, and to "Sheet 1" mid-sentence.
SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[A-Z(\u201c\"])")

# Says a thing is not in the graph. Applied only to a sentence that already
# names the multiplier's own percentage.
ABSENCE_PATTERNS = (
    r"do(?:es)? not represent",
    r"not represented",
    r"is missing",
    r"are missing",
    r"nothing in the graph reflects",
    r"not model(?:l)?ed",
    r"is absent",
    r"are absent",
    r"\babsent\b",
    r"no way",
    r"not present",
    r"not captured",
    r"not expressed",
    r"\bdeferred\b",
)
ABSENCE = re.compile("|".join(ABSENCE_PATTERNS), re.IGNORECASE)

# Says a thing IS in the graph. Tested against the sentence with the absence
# matches cut out, so "does not represent" cannot read as "represent".
PRESENCE_PATTERNS = (
    r"is model(?:l)?ed",
    r"are model(?:l)?ed",
    r"now model(?:l)?ed",
    r"model(?:l)?ed (?:here|as|by|in)",
    r"is represented",
    r"are represented",
    r"this filing (?:carries|represents|models|captures)",
    r"is expressed",
    r"is present",
    r"reflected in the graph",
)
PRESENCE = re.compile("|".join(PRESENCE_PATTERNS), re.IGNORECASE)

# --- MANIFEST-PROSE -------------------------------------------------------
# The one heading this corpus writes on purpose to declare what a filing defers,
# in both spellings it uses: "## Modeling deferrals" and, older,
# "Modeling deferrals (shared with TOU-D filings, tracked separately):".
PROSE_HEADING = re.compile(r"^\s*(?:#{1,6}\s*)?modeling deferrals\b", re.IGNORECASE)
# Any other markdown heading ends the section.
MD_HEADING = re.compile(r"^\s*#{1,6}\s")
PROSE_BULLET = re.compile(r"^\s*[-*•]\s+")

# An item that says the named thing is in the graph. Punctuation between the
# participle and the preposition is allowed because the corpus writes
# "MODELED, as urpx:minimumTenure" and "Modeled at us/ca/sce/electricity/care/".
ITEM_PRESENCE = re.compile(
    r"model(?:l)?ed[,;:]?\s+(?:here|as|at|by|in|on|under)\b"
    r"|\bis model(?:l)?ed\b|\bare model(?:l)?ed\b|\bnow model(?:l)?ed\b"
    r"|\bis captured\b|\bis represented\b",
    re.IGNORECASE)
# The same words with the sense reversed, which only the words immediately
# before the phrase distinguish: "Not modeled here." is the opposite claim.
# Up to two words may sit between the negator and the phrase, because "not yet
# modeled", "no longer modeled" and "not currently modeled" are all absence and
# strict adjacency would read the last two as presence. A contrastive
# conjunction in that gap ends the negated clause, so "not represented
# structurally, but modeled at us/ca/..." is a presence claim and not a negated
# one.
ITEM_NEGATED = re.compile(
    r"\b(?:not|never|neither|nor|no)\b"
    r"(?:\s+(?!but\b|however\b|although\b|though\b|while\b|whereas\b)[\w.,;-]+){0,2}"
    r"\s*$",
    re.IGNORECASE)
# A presence claim that also names a plan is not a statement about the graph.
# "modeled in a future cross-utility GHG-ARR modifier issue" and "not yet
# modeled as an EligibilityRule" both match ITEM_PRESENCE and neither is one.
ITEM_FUTURE = re.compile(r"\bfuture\b|\bwill be\b|\bnot yet\b|\bto be\b|\bplanned\b",
                         re.IGNORECASE)
# Neither is a claim whose WHERE is an issue tracker. An epic is the place this
# project records what it has not modeled, so "modeled as standalone
# RatePlanModifiers in the grid-coordination/urpx-rate-plans#13 secondary epic"
# is a deferral that names its own ticket.
ITEM_TRACKER = re.compile(
    r"[\w.-]+/[\w.-]+#\d+"          # grid-coordination/urpx-rate-plans#13
    r"|(?<!\w)#\d+\b"               # a bare #13
    r"|\bepic\b|\bissue\b|\bticket\b|\btracked\b|\bbacklog\b|\bmilestone\b",
    re.IGNORECASE)

# The two forms of WHERE this corpus can resolve. A corpus path must be a
# directory holding a filing; a urpx: term must appear in the JSON-LD of this
# filing or of a path the item names. Anything else names no checkable place.
CORPUS_PATH = re.compile(
    r"(?<![\w/])(?:" + "|".join(re.escape(r) for r in corpus.COUNTRY_ROOTS)
    + r")/(?:[A-Za-z0-9._-]+/)+")
URPX_TERM = re.compile(r"\burpx:[A-Za-z][A-Za-z0-9_-]*")


# --------------------------------------------------------------------------
# JSON-LD traversal
# --------------------------------------------------------------------------

def node_type(node: dict):
    t = node.get("@type")
    if isinstance(t, str):
        return t
    if isinstance(t, list) and t:
        return t[0]
    return None


def walk(node, fn, path=()):
    """Depth-first over a JSON-LD document, carrying the property path.

    List indices are dropped from the path, so a claim under a one-element
    @graph array and one under a bare object compare equal.
    """
    if isinstance(node, dict):
        fn(node, path)
        for k, v in node.items():
            if k == "@context":
                continue
            walk(v, fn, path + (k,))
    elif isinstance(node, list):
        for v in node:
            walk(v, fn, path)


def collect(doc, predicate):
    out = []
    walk(doc, lambda n, p: out.append((n, p)) if predicate(n, p) else None)
    return out


def claim_result(claim: dict):
    res = claim.get("urpx:completenessResult")
    if isinstance(res, dict):
        return res.get("@id")
    return res if isinstance(res, str) else None


def evaluation_text(claim: dict) -> str | None:
    ev = claim.get("urpx:explainedBy")
    if isinstance(ev, list):
        ev = ev[0] if ev else None
    if isinstance(ev, dict):
        d = ev.get("urpx:description")
        if isinstance(d, str) and d.strip():
            return d
    return None


