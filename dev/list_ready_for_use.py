#!/usr/bin/env python3
"""Generate reports/ready-for-use.{md,edn} from tariff.toml [modeling] blocks.

A filing-directory is "ready for use" iff its tariff.toml has
`[modeling].complete = true` (which by schema implies `deferrals = []`).

Per-tariff.toml-directory granularity: when a directory contains both a
base RatePlan and an inline RatePlanModifier (e.g. PG&E E-TOU-C 2026-03-01
with the baseline-tier modifier alongside the base), the [modeling] block
aggregates across both jsonld files — if either has deferrals, the whole
filing is not "ready". That's stricter than a per-jsonld-file scan but
matches the granularity of the [modeling] block.

Run from repo root:  python3 dev/list_ready_for_use.py
"""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import corpus

import tomli

REPO = Path(__file__).resolve().parent.parent

UTILITY_ORDER = ["pge", "sce", "sdge", "cpau", "smud", "ladwp"]
UTILITY_LABEL = {
    "pge":   "PG&E (IOU)",
    "sce":   "SCE (IOU)",
    "sdge":  "SDG&E (IOU)",
    "cpau":  "CPAU (POU)",
    "smud":  "SMUD (POU)",
    "ladwp": "LADWP (POU)",
}


def collect() -> tuple[list[dict], int]:
    """Return (ready_filings, total_filings)."""
    ready: list[dict] = []
    total = 0
    for tp in corpus.tariff_tomls():
        total += 1
        with tp.open("rb") as fp:
            data = tomli.load(fp)
        m = data.get("modeling") or {}
        if m.get("complete") is not True:
            continue
        parts = tp.relative_to(REPO).parts
        utility, schedule, date = parts[2], parts[3], parts[5]
        d = tp.parent
        has_base = any(d.glob("rate-plan_*.jsonld"))
        has_mod = any(d.glob("rate-plan-modifier_*.jsonld"))
        if has_base:
            typ = "rate-plan"
        elif has_mod:
            typ = "modifier"
        else:
            typ = "unknown"
        ready.append({
            "utility": utility,
            "schedule": schedule,
            "type": typ,
            "date": date,
        })
    return ready, total


# ---------------------------------------------------------------------------
# EDN
# ---------------------------------------------------------------------------

def render_edn(ready: list[dict]) -> str:
    if not ready:
        return "[]\n"
    uw = max(len(r["utility"]) for r in ready)
    sw = max(len(r["schedule"]) for r in ready)
    tw = max(len(r["type"]) for r in ready)

    header = (
        ";; Auto-generated by dev/list_ready_for_use.py — do not edit by hand.\n"
        ";;\n"
        ';; A filing-directory is "ready for use" iff its tariff.toml has\n'
        ";; [modeling].complete = true (per LAYOUT.md §4.4).\n"
        ";;\n"
        ";; Granularity is per-tariff.toml-directory: when a directory contains\n"
        ";; both a base RatePlan and an inline modifier, the [modeling] block\n"
        ";; aggregates — both must be deferral-free for the filing to qualify.\n"
        "\n"
    )

    lines = []
    for i, r in enumerate(ready):
        utility = f":{r['utility']}"
        schedule = f'"{r["schedule"]}"'
        typ = f":{r['type']}"
        date = f'"{r["date"]}"'
        prefix = "[" if i == 0 else " "
        lines.append(
            f"{prefix}{{:utility {utility:<{uw + 1}} "
            f":name {schedule:<{sw + 2}} "
            f":type {typ:<{tw + 1}} "
            f":date {date}}}"
        )
    return header + "\n".join(lines) + "]\n"


# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------

TYPE_LABEL = {"rate-plan": "RatePlan", "modifier": "RatePlanModifier"}


def render_md(ready: list[dict], total: int) -> str:
    by_utility: dict[str, list[dict]] = defaultdict(list)
    for r in ready:
        by_utility[r["utility"]].append(r)

    out: list[str] = []
    out.append("# Filings ready for use")
    out.append("")
    out.append(
        "Auto-generated by `dev/list_ready_for_use.py` from each filing's "
        "`tariff.toml [modeling]` block. Do not edit by hand."
    )
    out.append("")
    out.append(
        f'A filing-directory qualifies iff `[modeling].complete = true` '
        f"(per [LAYOUT.md §4.4](../LAYOUT.md)). "
        f"**{len(ready)} of {total}** filings qualify. "
        f"See [`ready-for-use.edn`](./ready-for-use.edn) for the machine-readable form."
    )
    out.append("")

    out.append("## By utility")
    out.append("")

    seen = []
    for u in UTILITY_ORDER:
        if u in by_utility:
            seen.append(u)
    # Append any utility we don't have an explicit ordering for, alphabetically
    for u in sorted(by_utility.keys()):
        if u not in seen:
            seen.append(u)

    for u in seen:
        rows = by_utility[u]
        label = UTILITY_LABEL.get(u, u.upper())
        out.append(f"### {label} — {len(rows)}")
        out.append("")
        out.append("| Schedule | Effective | Type |")
        out.append("|---|---|---|")
        for r in rows:
            out.append(f"| `{r['schedule']}` | {r['date']} | {TYPE_LABEL.get(r['type'], r['type'])} |")
        out.append("")

    out.append("## Caveats")
    out.append("")
    out.append(
        "- **Source of truth.** This list is derived from `[modeling].complete` in each "
        "`tariff.toml`. The flag is hand-curated by the modeler at the time the filing is "
        "written; it asserts only that the source PDF was fully captured in the JSON-LD, "
        "not that the filing has been independently reviewed (`[review].status` tracks that "
        "axis separately)."
    )
    out.append(
        "- **Per-directory granularity.** When a `versions/<date>/` directory contains both "
        "a base RatePlan and an inline `RatePlanModifier`, both must be deferral-free for "
        "the filing to qualify. A directory is one filing, not two."
    )
    out.append(
        "- **Modifier coverage is a separate axis.** A base RatePlan being ready does not "
        "imply that every modifier that legally attaches to it has its own filing — see "
        "[`modifier-coverage.md`](./modifier-coverage.md) for that view."
    )
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    ready, total = collect()

    edn_path = REPO / "reports" / "ready-for-use.edn"
    md_path = REPO / "reports" / "ready-for-use.md"
    edn_path.write_text(render_edn(ready))
    md_path.write_text(render_md(ready, total))
    print(f"wrote {edn_path.relative_to(REPO)} ({len(ready)} of {total})")
    print(f"wrote {md_path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
