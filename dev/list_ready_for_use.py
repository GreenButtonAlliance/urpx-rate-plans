"""Generate reports/ready-for-use.{md,edn}: can a price server use this filing?

The headline answers SERVABILITY, rolled up from reports/service-arrangements.md
via dev/arrangements.py. It used to answer `[modeling].complete` instead, which
LAYOUT.md 4.4 defines as "does this JSON-LD fully capture its source PDF(s)?".
That is a real question and a different one, and reading it as readiness had it
reporting 1 of 72, because the flag counts administrative provisions alongside
pricing ones. CPAU E-2 is incomplete over a demand-meter threshold (its own
deferral: a demand meter is installed once monthly use exceeds 8,000 kWh for
three consecutive months), which changes nobody's per-kWh price. In the other
direction, pge:e-tou-c@2026-03-27 carried complete = true at 03f5ec3 while,
per a3e3007, it had been derived from a sibling that double-counted the Baseline
Credit. So `complete` stays, as its own column, clearly labeled.

Granularity is one row per tariff.toml directory, because that is what a filing
is. A directory's servability is the best outcome over every arrangement drawing
on a version node it holds: the question is whether a price server can get a
price out of this filing at all.

Run from repo root:  python3 dev/list_ready_for_use.py
"""
from __future__ import annotations

import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import arrangements as A
import utilities  # noqa: E402

REPO = Path(__file__).resolve().parent.parent

# Order and labels come from dev/utilities.py. This block used to be a
# byte-identical copy in two generators, and its roster was not checked against
# the corpus, so a utility gaining filings dropped out of the report silently.
UTILITY_ORDER = utilities.ORDER
UTILITY_LABEL = utilities.labels()
SERVES_LABEL = {
    A.SERVABLE: "servable",
    A.NOT_PRICED: "not priced per kWh",
    A.BLOCKED: "blocked",
    A.UNMEASURED: "not measured",
    A.SUPERSEDED: "superseded",
}
SERVES_KW = {
    A.SERVABLE: "servable",
    A.NOT_PRICED: "not-priced-per-kwh",
    A.BLOCKED: "blocked",
    A.UNMEASURED: "not-measured",
    A.SUPERSEDED: "superseded",
}


def render_md(d: dict) -> str:
    rows = d["filings"]
    tally = collections.Counter(r["outcome"] for r in rows)
    complete = sum(1 for r in rows if r["complete"])
    instants = d["baseline"]["instants"]

    o: list[str] = []
    w = o.append
    w("# Filings ready for use")
    w("")
    w("Auto-generated by `dev/list_ready_for_use.py`. Do not edit by hand.")
    w("")
    w(f"**{tally[A.SERVABLE]} of {len(rows)}** filing directories take part in at least one servable "
      f"service arrangement: a price server asking them for a price at any of the "
      f"{len(instants)} probe instants gets a number back. See "
      f"[`service-arrangements.md`](./service-arrangements.md) for the arrangements themselves and "
      f"[`ready-for-use.edn`](./ready-for-use.edn) for the machine-readable form.")
    w("")
    w("## Two axes, deliberately not collapsed")
    w("")
    w("**Servable** answers: can a price server resolve this to a price? It is read from "
      "`dev/baseline/marginal-rates.edn` through the service-arrangement enumeration, over current "
      "versions only.")
    w("")
    w("**Captures its source PDF** is `[modeling].complete` in the filing's own `tariff.toml`, which "
      "[LAYOUT.md §4.4](../LAYOUT.md) defines as *does this JSON-LD fully capture its source PDF(s)?* "
      "It is hand-curated by whoever modeled the filing against its source.")
    w("")
    w(f"The two do not track each other and must not be collapsed. {complete} of {len(rows)} filings "
      f"carry `complete = true`, because the flag counts administrative provisions alongside pricing "
      f"ones: a filing can be incomplete over a demand-meter threshold that changes nobody's bill, "
      f"and a filing can be complete while getting a price wrong. LAYOUT.md §4.4 makes the general "
      f"argument: *collapsing them into a single ready flag forces the modeler to pick one axis and "
      f"lie about the other.*")
    w("")

    w("## Summary")
    w("")
    w("| Servability | Filings |")
    w("|---|---:|")
    for k in (A.SERVABLE, A.NOT_PRICED, A.BLOCKED, A.UNMEASURED, A.SUPERSEDED):
        if tally[k]:
            w(f"| {SERVES_LABEL[k]} | {tally[k]} |")
    w(f"| **total** | {len(rows)} |")
    w("")
    w("- **servable** at least one arrangement drawing on this filing resolves at every probe instant.")
    w("- **not priced per kWh** the filing resolves and legitimately prices nothing per kWh. CPAU E-14 "
      "and E-16 are street lighting. This is not a defect.")
    w("- **blocked** every arrangement drawing on this filing refuses, for a reason that is a gap or "
      "an undecided selection.")
    w("- **not measured** no arrangement drawing on this filing has a baseline row.")
    w("- **superseded** every version node in this filing has been superseded by a later one, so "
      "nobody takes service under it and it is not a service arrangement.")
    w("")

    w("## By utility")
    w("")
    by_utility: dict[str, list[dict]] = collections.defaultdict(list)
    for r in rows:
        by_utility[r["utility"]].append(r)
    order = [u for u in UTILITY_ORDER if u in by_utility]
    order += [u for u in sorted(by_utility) if u not in order]

    for u in order:
        group = sorted(by_utility[u], key=lambda r: (r["schedule"], r["date"]))
        servable = sum(1 for r in group if r["outcome"] == A.SERVABLE)
        w(f"### {UTILITY_LABEL.get(u, u.upper())}: {servable} of {len(group)} servable")
        w("")
        w("| Schedule | Effective | Servability | Arrangements drawing on it | Captures its source PDF | Notes |")
        w("|---|---|---|---:|---|---|")
        for r in group:
            w(f"| `{r['schedule']}` | {r['date']} | {SERVES_LABEL[r['outcome']]} | "
              f"{r['arrangements']} | {'yes' if r['complete'] else 'no'} | {r['reason']} |")
        w("")

    w("## Caveats")
    w("")
    w(f"- **As of the recorded baseline.** Servability is read from "
      f"`dev/baseline/marginal-rates.edn`, {len(instants)} probe instants per key, resolved by "
      f"clj-urpx {d['baseline']['clj_urpx_version']}. Nothing is re-resolved here.")
    w("- **Per-directory granularity.** A directory is one filing, not one version. It can hold a "
      "base RatePlan and the modifiers operative at its snapshot date, and a version node can appear "
      "in more than one directory.")
    w("- **Servable is not reviewed.** `[review].status` tracks whether a person has checked the "
      "filing, and neither column here reads it.")
    w("- **Modifier coverage is a separate axis again.** A base RatePlan being servable does not imply "
      "that every modifier that legally attaches to it has its own filing. See "
      "[`modifier-coverage.md`](./modifier-coverage.md).")
    return "\n".join(o) + "\n"


def render_edn(d: dict) -> str:
    rows = sorted(d["filings"], key=lambda r: (r["utility"], r["schedule"], r["date"]))
    tally = collections.Counter(r["outcome"] for r in rows)
    o: list[str] = []
    w = o.append
    w(";; Auto-generated by dev/list_ready_for_use.py. Do not edit by hand.")
    w(";;")
    w(";; One row per tariff.toml directory.")
    w(";;")
    w(";; :serves answers CAN A PRICE SERVER RESOLVE THIS TO A PRICE, rolled up from")
    w(";; reports/service-arrangements.edn: the best outcome over every service")
    w(";; arrangement drawing on a version node this filing holds.")
    w(";;   :servable           some arrangement resolves at every probe instant")
    w(";;   :not-priced-per-kwh resolves, and legitimately prices nothing per kWh")
    w(";;   :blocked            refuses: a gap or an undecided selection")
    w(";;   :not-measured       no arrangement here has a baseline row")
    w(";;   :superseded         every version node here has been superseded")
    w(";;")
    w(";; :captures-source-pdf is [modeling].complete from the filing's own")
    w(";; tariff.toml, a DIFFERENT question (LAYOUT.md 4.4): does the JSON-LD fully")
    w(";; capture its source PDF? The two axes are deliberately not collapsed.")
    w("")
    w("{:totals")
    w("  {" + " ".join(f":{SERVES_KW[k]} {tally[k]}"
                       for k in (A.SERVABLE, A.NOT_PRICED, A.BLOCKED, A.UNMEASURED, A.SUPERSEDED)
                       if tally[k])
      + f" :filings {len(rows)}"
      + f" :captures-source-pdf {sum(1 for r in rows if r['complete'])}}}")
    w("")
    w(" :filings")
    w(" [")
    uw = max(len(r["utility"]) for r in rows)
    sw = max(len(r["schedule"]) for r in rows)
    vw = max(len(SERVES_KW[r["outcome"]]) for r in rows)
    for r in rows:
        utility = f":{r['utility']}"
        schedule = f'"{r["schedule"]}"'
        w(f"  {{:utility {utility:<{uw + 1}} "
          f":name {schedule:<{sw + 2}} "
          f':date "{r["date"]}" '
          f":serves :{SERVES_KW[r['outcome']]:<{vw + 1}} "
          f":arrangements {r['arrangements']:<3} "
          f":captures-source-pdf {'true' if r['complete'] else 'false'}}}")
    w(" ]}")
    return "\n".join(o) + "\n"


def main() -> int:
    d = A.build()
    edn_path = REPO / "reports" / "ready-for-use.edn"
    md_path = REPO / "reports" / "ready-for-use.md"
    edn_path.write_text(render_edn(d))
    md_path.write_text(render_md(d))
    tally = collections.Counter(r["outcome"] for r in d["filings"])
    print(f"wrote {md_path.relative_to(REPO)} and {edn_path.relative_to(REPO)}: "
          f"{tally[A.SERVABLE]} of {len(d['filings'])} filings servable "
          f"({sum(1 for r in d['filings'] if r['complete'])} capture their source PDF)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
