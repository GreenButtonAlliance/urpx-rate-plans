"""Generate reports/rate-plans-to-model.md: the backlog, from inventory minus corpus.

Answers one question per row: this schedule is known to exist, is it modeled
here? What makes the answer trustworthy is where the inventory came from, so
each utility's section says that first. A utility with an inventory source has a
real denominator and a real percentage; one without has neither, and this report
says so rather than computing a number that looks like progress.

Reads data/inventories/ (dev/build_inventory.py) and the corpus. Writes no
filing and assigns no identifier.

Run from repo root:  python3 dev/list_rate_plans_to_model.py
"""
from __future__ import annotations

import json
import re
import sys
import urllib.parse
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 and earlier
    import tomli as tomllib

import corpus

REPO = Path(__file__).resolve().parent.parent
INV = REPO / "data" / "inventories"


def plural(n: int, one: str, many: str) -> str:
    return f"{n} {one if n == 1 else many}"


def nk(u: str):
    """Document identity, so one PDF linked two ways is one document."""
    q = urllib.parse.urlparse(u.lower())
    return (q.netloc.removeprefix("www."), urllib.parse.unquote(q.path).replace(" ", ""))


def modeled_schedules() -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for jsonld in corpus.all_filing_jsonld():
        util, sched, _ = corpus.parse_filing_path(jsonld)
        out.setdefault(util, set()).add(sched)
    corpus.require_nonempty(out, "modeled schedules")
    return out


def attribute_by_source(invs) -> dict[str, dict[str, set[str]]]:
    """Which corpus directories model which inventory schedule, by source URL.

    A directory name need not match a publisher's schedule code, and for SCE it
    usually does not: six directories (tou-d-4-9pm, tou-d-5-8pm, tou-d-prime,
    tou-d-prime-cpp, deed-restricted, fera) are all modeled from the single
    ELECTRIC_SCHEDULES_TOU-D.pdf, and care is modeled from D-CARE. Matching a
    filing's recorded [source] url against the inventory's document URL settles
    that without guessing at names.
    """
    by_doc: dict[str, dict] = {}
    for d in invs:
        for sch, rec in d["schedules"].items():
            for src in rec.get("sources", {}).values():
                if src.get("document_url"):
                    by_doc.setdefault(d["utility"], {})[nk(src["document_url"])] = sch
    out: dict[str, dict[str, set[str]]] = {}
    for toml in (REPO / "us").glob("*/*/*/*/versions/*/tariff.toml"):
        try:
            util, sched, _ = corpus.parse_filing_path(toml)
        except ValueError:
            continue
        url = (tomllib.loads(toml.read_text()).get("source") or {}).get("url")
        if not url:
            continue
        hit = by_doc.get(util, {}).get(nk(url))
        if hit:
            out.setdefault(util, {}).setdefault(hit, set()).add(sched)
    return out


def main() -> int:
    if not INV.exists() or not any(INV.glob("*.json")):
        print("REFUSING: no inventories. Run dev/build_inventory.py first.", file=sys.stderr)
        return 3
    modeled = modeled_schedules()
    docs = {}
    dpath = REPO / "data" / "documents.json"
    if dpath.exists():
        # Key on the document, not the URL string: the same PDF is linked as
        # pge.com by one source and www.pge.com by another.
        def nk(u):
            q = urllib.parse.urlparse(u.lower())
            return (q.netloc.removeprefix("www."),
                    urllib.parse.unquote(q.path).replace(" ", ""))
        for d in json.loads(dpath.read_text())["documents"]:
            if d.get("sha256") or nk(d["url"]) not in docs:
                docs[nk(d["url"])] = d

    invs = [json.loads(f.read_text()) for f in sorted(INV.glob("*.json"))]
    via_source = attribute_by_source(invs)
    o = ["# Rate plans to model", "",
         "Auto-generated by `dev/list_rate_plans_to_model.py` from `data/inventories/` and the "
         "corpus. Do not edit by hand.", "",
         "A row is a schedule some source says exists. The question each answers is whether "
         "this corpus models it. **Where the inventory came from decides what the numbers "
         "mean**, so each section says that before it counts anything: a utility whose own "
         "tariff book was read has a real denominator, and a utility known only through a "
         "third-party feed does not.", ""]

    # Summary, with the two kinds kept apart rather than added together.
    real = [d for d in invs if d.get("has_inventory_source")]
    obs = [d for d in invs if not d.get("has_inventory_source")]
    if real:
        n = sum(len(d["schedules"]) for d in real)
        m = sum(len(modeled.get(d["utility"], set()) & set(d["schedules"])) for d in real)
        o += [f"**{m} of {n} schedules modeled** across "
              f"{plural(len(real), 'utility', 'utilities')} whose own schedule list "
              f"was read ({100*m//max(1,n)}%).", ""]
    if obs:
        o += [f"{plural(len(obs), 'further utility is', 'further utilities are')} known "
              f"only through an observed feed, carrying "
              f"{sum(len(d['schedules']) for d in obs)} named schedules whose completeness "
              f"is unknown. Those are not in the percentage above.", ""]

    for d in sorted(invs, key=lambda x: (not x.get("has_inventory_source"), x["utility"])):
        util, scheds = d["utility"], d["schedules"]
        mine = modeled.get(util, set())
        attributed = via_source.get(util, {})
        # A schedule is modeled if a directory of that name exists OR a filing
        # cites its document. The second is what catches a corpus directory
        # named differently from the publisher's schedule code.
        covered = (set(scheds) & mine) | set(attributed)
        hit = sorted(covered)
        miss = sorted(set(scheds) - covered)
        explained = {dirname for dirs in attributed.values() for dirname in dirs}
        extra = sorted(mine - set(scheds) - explained)
        o += [f"## {util}", ""]
        if d.get("has_inventory_source"):
            # The sources that actually named a schedule HERE, not every source
            # the run invoked: sources_run is global and listing it per utility
            # credited PG&E's tariff book with SCE's schedules.
            used = sorted({k for r in scheds.values() for k in r.get("sources", {})})
            srcs = ", ".join(f"`{x}`" for x in used) or "no source"
            closed = sum(1 for r in scheds.values()
                         if any(v.get("status") == "closed" for v in r.get("sources", {}).values()))
            line = f"Inventory read from {srcs}. {len(hit)} of {len(scheds)} modeled."
            if closed:
                line += (f" {closed} of the {len(scheds)} are closed to new enrollment, "
                         f"which the publisher states; the rest are current.")
            o += [line, ""]
        else:
            o += [f"**No inventory source.** Every schedule below is a name observed in a "
                  f"feed, not a list {util} published, so this is neither complete nor "
                  f"necessarily at schedule granularity. {len(hit)} of {len(scheds)} "
                  f"observed names are modeled; that fraction is not a coverage figure.", ""]
        multi = {k: sorted(v) for k, v in attributed.items() if len(v) > 1 or k not in mine}
        if multi:
            o += ["Directories this corpus models under a name the publisher does not use, "
                  "matched by the document each filing cites:", ""]
            for sch, dirs in sorted(multi.items()):
                o.append(f"- `{sch}` is modeled by " + ", ".join(f"`{x}`" for x in dirs))
            o.append("")
        if extra:
            o += [f"Modeled here, cited no document this inventory names: "
                  f"{', '.join('`'+e+'`' for e in extra)}. Each is either a schedule the "
                  f"inventory misses or a filing sourced from somewhere else.", ""]
        if miss:
            any_status = any(v.get("status") for r in scheds.values()
                             for v in r.get("sources", {}).values())
            head = "| Schedule | Code | Document | Demand signal |"
            rule = "|---|---|---|---:|"
            if any_status:
                head = "| Schedule | Code | Status | Document | Demand signal |"
                rule = "|---|---|---|---|---:|"
            o += [head, rule]
            def demand(s):
                return sum(x.get("midas_identifiers", 0)
                           for x in scheds[s].get("observed", [])) or \
                       sum(x.get("midas_identifiers", 0) for x in scheds[s].get("sources", {}).values())
            for s in sorted(miss, key=lambda s: (-demand(s), s)):
                rec = scheds[s]
                src = next(iter(rec.get("sources", {}).values()), {})
                url = src.get("document_url")
                have = docs.get(nk(url), {}).get("sha256") if url else None
                link = (f"[{'fetched' if have else 'link'}]({url})" if url else "none")
                n = demand(s)
                if any_status:
                    st = next((v.get("status") for v in rec.get("sources", {}).values()
                               if v.get("status")), "unstated")
                    o.append(f"| `{s}` | {src.get('code','?')} | {st} | {link} | {n or '—'} |")
                else:
                    o.append(f"| `{s}` | {src.get('code','?')} | {link} | {n or '—'} |")
            o.append("")
        if d.get("unmatched"):
            o += [f"<details><summary>{len(d['unmatched'])} observed name(s) matching no "
                  f"schedule</summary>", "",
                  "Either a gap in the inventory or a name this corpus does not understand. "
                  "Listed rather than dropped.", "",
                  ", ".join(f"`{u['code']}`" for u in d["unmatched"]), "", "</details>", ""]

    named = {d["utility"] for d in invs}
    missing = sorted(set(modeled) - named)
    if missing:
        o += ["## Utilities with filings but no inventory", "",
              "Modeled here, with no source yet read that says what else they publish: "
              + ", ".join(f"`{m}`" for m in missing) + ".",
              "Adding a source for one of these is what turns its filings into a fraction "
              "of a known whole.", ""]

    (REPO / "reports" / "rate-plans-to-model.md").write_text("\n".join(o) + "\n")
    tot = sum(len(d["schedules"]) for d in invs)
    mod = sum(len(modeled.get(d["utility"], set()) & set(d["schedules"])) for d in invs)
    print(f"wrote reports/rate-plans-to-model.md: {tot} schedules known, {mod} modeled, "
          f"{plural(len(real), 'utility', 'utilities')} with a real inventory")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
