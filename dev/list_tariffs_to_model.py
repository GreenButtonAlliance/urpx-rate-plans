"""Generate reports/tariffs-to-model.md: the backlog, from inventory minus corpus.

Answers one question per row: this schedule is known to exist, is it modeled
here? What makes the answer trustworthy is where the inventory came from, so
each utility's section says that first. A utility with an inventory source has a
real denominator and a real percentage; one without has neither, and this report
says so rather than computing a number that looks like progress.

Reads data/inventories/ (dev/build_inventory.py) and the corpus. Writes no
filing and assigns no identifier.

Run from repo root:  python3 dev/list_tariffs_to_model.py
"""
from __future__ import annotations

import json
import re
import sys
import urllib.parse
from pathlib import Path

import corpus

REPO = Path(__file__).resolve().parent.parent
INV = REPO / "data" / "inventories"


def plural(n: int, one: str, many: str) -> str:
    return f"{n} {one if n == 1 else many}"


def modeled_schedules() -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for jsonld in corpus.all_filing_jsonld():
        util, sched, _ = corpus.parse_filing_path(jsonld)
        out.setdefault(util, set()).add(sched)
    corpus.require_nonempty(out, "modeled schedules")
    return out


def main() -> int:
    if not INV.exists() or not any(INV.glob("*.json")):
        print("REFUSING: no inventories. Run dev/build_inventory.py first.", file=sys.stderr)
        return 3
    modeled = modeled_schedules()
    docs = {}
    dpath = REPO / "data" / "documents.json"
    if dpath.exists():
        # Key on the document, not the URL string: the same PDF is linked as
        # pge.com by one source and www.pge.com by another.
        def nk(u):
            q = urllib.parse.urlparse(u.lower())
            return (q.netloc.removeprefix("www."),
                    urllib.parse.unquote(q.path).replace(" ", ""))
        for d in json.loads(dpath.read_text())["documents"]:
            if d.get("sha256") or nk(d["url"]) not in docs:
                docs[nk(d["url"])] = d

    invs = [json.loads(f.read_text()) for f in sorted(INV.glob("*.json"))]
    o = ["# Tariffs to model", "",
         "Auto-generated by `dev/list_tariffs_to_model.py` from `data/inventories/` and the "
         "corpus. Do not edit by hand.", "",
         "A row is a schedule some source says exists. The question each answers is whether "
         "this corpus models it. **Where the inventory came from decides what the numbers "
         "mean**, so each section says that before it counts anything: a utility whose own "
         "tariff book was read has a real denominator, and a utility known only through a "
         "third-party feed does not.", ""]

    # Summary, with the two kinds kept apart rather than added together.
    real = [d for d in invs if d.get("has_inventory_source")]
    obs = [d for d in invs if not d.get("has_inventory_source")]
    if real:
        n = sum(len(d["schedules"]) for d in real)
        m = sum(len(modeled.get(d["utility"], set()) & set(d["schedules"])) for d in real)
        o += [f"**{m} of {n} schedules modeled** across "
              f"{plural(len(real), 'utility', 'utilities')} whose own schedule list "
              f"was read ({100*m//max(1,n)}%).", ""]
    if obs:
        o += [f"{plural(len(obs), 'further utility is', 'further utilities are')} known "
              f"only through an observed feed, carrying "
              f"{sum(len(d['schedules']) for d in obs)} named schedules whose completeness "
              f"is unknown. Those are not in the percentage above.", ""]

    for d in sorted(invs, key=lambda x: (not x.get("has_inventory_source"), x["utility"])):
        util, scheds = d["utility"], d["schedules"]
        mine = modeled.get(util, set())
        hit = sorted(set(scheds) & mine)
        miss = sorted(set(scheds) - mine)
        extra = sorted(mine - set(scheds))
        o += [f"## {util}", ""]
        if d.get("has_inventory_source"):
            srcs = ", ".join(f"`{s}`" for s in d["sources_run"])
            o += [f"Inventory read from {srcs}. {len(hit)} of {len(scheds)} modeled.", ""]
        else:
            o += [f"**No inventory source.** Every schedule below is a name observed in a "
                  f"feed, not a list {util} published, so this is neither complete nor "
                  f"necessarily at schedule granularity. {len(hit)} of {len(scheds)} "
                  f"observed names are modeled; that fraction is not a coverage figure.", ""]
        if extra:
            o += [f"Modeled here but not named by any source: {', '.join('`'+e+'`' for e in extra)}. "
                  f"Each is either a schedule the inventory misses or a directory named "
                  f"differently from how the source spells it.", ""]
        if miss:
            o += ["| Schedule | Code | Document | Demand signal |", "|---|---|---|---:|"]
            def demand(s):
                return sum(x.get("midas_identifiers", 0)
                           for x in scheds[s].get("observed", [])) or \
                       sum(x.get("midas_identifiers", 0) for x in scheds[s].get("sources", {}).values())
            for s in sorted(miss, key=lambda s: (-demand(s), s)):
                rec = scheds[s]
                src = next(iter(rec.get("sources", {}).values()), {})
                url = src.get("document_url")
                have = docs.get(nk(url), {}).get("sha256") if url else None
                link = (f"[{'fetched' if have else 'link'}]({url})" if url else "none")
                n = demand(s)
                o.append(f"| `{s}` | {src.get('code','?')} | {link} | {n or '—'} |")
            o.append("")
        if d.get("unmatched"):
            o += [f"<details><summary>{len(d['unmatched'])} observed name(s) matching no "
                  f"schedule</summary>", "",
                  "Either a gap in the inventory or a name this corpus does not understand. "
                  "Listed rather than dropped.", "",
                  ", ".join(f"`{u['code']}`" for u in d["unmatched"]), "", "</details>", ""]

    named = {d["utility"] for d in invs}
    missing = sorted(set(modeled) - named)
    if missing:
        o += ["## Utilities with filings but no inventory", "",
              "Modeled here, with no source yet read that says what else they publish: "
              + ", ".join(f"`{m}`" for m in missing) + ".",
              "Adding a source for one of these is what turns its filings into a fraction "
              "of a known whole.", ""]

    (REPO / "reports" / "tariffs-to-model.md").write_text("\n".join(o) + "\n")
    tot = sum(len(d["schedules"]) for d in invs)
    mod = sum(len(modeled.get(d["utility"], set()) & set(d["schedules"])) for d in invs)
    print(f"wrote reports/tariffs-to-model.md: {tot} schedules known, {mod} modeled, "
          f"{plural(len(real), 'utility', 'utilities')} with a real inventory")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
